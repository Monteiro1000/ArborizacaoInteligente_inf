function normalizeIconKey(rawName) {
  if (!rawName) return 'tree';
  return rawName.replace(/^ic-/, '').replace(/-duotone$/, '');
}

export function Icon({
  name,
  size = 'md',
  className = '',
  title,
  ariaHidden = true
}) {
  const baseKey = normalizeIconKey(name);
  const def = ICON_DEFINITIONS[baseKey] || ICON_DEFINITIONS['tree'];

  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox={def.viewBox}
      className={`ic-svg ic-${size} ${className}`.trim()}
      aria-hidden={title ? undefined : ariaHidden}
      role={title ? 'img' : undefined}
      focusable="false"
    >
      {title && <title>{title}</title>}
      {def.content}
    </svg>
  );
}

export default function IconSprite() {
  return (
    <svg
      id="ic-sprite-root"
      className="ic-sprite-defs"
      xmlns="http://www.w3.org/2000/svg"
      width="0"
      height="0"
      style={{
        display: 'none',
        position: 'absolute',
        width: 0,
        height: 0,
        overflow: 'hidden',
        pointerEvents: 'none'
      }}
      aria-hidden="true"
      focusable="false"
    >
      {Object.entries(ICON_DEFINITIONS).map(([key, def]) => {
        const canonicalId = key === 'satellite' ? 'ic-satellite' : `ic-${key}-duotone`;
        const shortId = `ic-${key}`;
        return (
          <React.Fragment key={key}>
            <symbol id={canonicalId} viewBox={def.viewBox}>
              {def.content}
            </symbol>
            {canonicalId !== shortId && (
              <symbol id={shortId} viewBox={def.viewBox}>
                {def.content}
              </symbol>
            )}
          </React.Fragment>
        );
      })}
    </svg>
  );
}
